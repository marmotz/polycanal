import type {
  BindingEmitter,
  CodeImport,
  GeneratedCode,
  JsonSchema,
  SchemaGenerationContext,
  ValidationDriver,
} from '@polycanal/core';
import {
  type ActionDescription,
  type ContractDescription,
  type EventDescription,
  type InputDescription,
  type OperationDescription,
  operationId,
  SCHEMA_REF_PREFIX,
} from './description.js';
import { hoistDefinitions } from './hoist.js';

export interface GenerateOptions {
  /** Validation library the schemas are generated for. */
  readonly validation: ValidationDriver;
  /** Code emitters of the bindings, one per driver (e.g. `restBindingEmitter`). */
  readonly bindings: readonly BindingEmitter[];
  /** Name of the exported contract. Default: `contract`. */
  readonly exportName?: string;
  /** First comment of the file. */
  readonly banner?: string;
}

const DEFAULT_BANNER = 'Generated by Polycanal. Do not edit: regenerate instead.';

interface TreeNode {
  readonly children: Map<string, TreeNode | OperationDescription>;
}

/** Generates the TypeScript source of a contract: imports, named schemas, then `defineContract()`. */
export function generateContractSource(description: ContractDescription, options: GenerateOptions): string {
  const { schemas, operations } = hoistDefinitions(description);
  const imports = new ImportSet();
  const identifiers = schemaIdentifiers(Object.keys(schemas));
  const emitted = new Set<string>();
  const context: SchemaGenerationContext = {
    resolveRef: (ref) => identifiers.get(refName(ref)) ?? fail(`unknown schema reference "${ref}"`),
    isLazyRef: (ref) => !emitted.has(refName(ref)),
  };
  const schema = (value: JsonSchema): string => imports.use(options.validation.generate(value, context));
  const emitters = new Map(options.bindings.map((emitter) => [emitter.driver, emitter]));

  const declarations = Object.entries(schemas).map(([name, value]) => {
    const code = `export const ${identifiers.get(name)} = ${schema(value)};`;
    emitted.add(name);

    return code;
  });

  // Every named schema is declared before the contract: references from operations never need to be lazy
  const operation = (value: OperationDescription): string => {
    const emitter = emitters.get(value.binding.driver);

    if (emitter === undefined) {
      fail(`${operationId(value)}: no binding emitter for driver "${value.binding.driver}"`);
    }

    const transport = imports.use(emitter.emit(value.binding));

    return value.family === 'action'
      ? actionCode(value, transport, schema, options.validation, imports)
      : eventCode(value, transport, schema, imports);
  };

  const tree = buildTree(operations);
  imports.add({ from: '@polycanal/core', names: ['defineContract'] });
  const contract = `export const ${options.exportName ?? 'contract'} = defineContract(${treeCode(tree, operation)});`;

  return [
    `// ${options.banner ?? DEFAULT_BANNER}`,
    '',
    imports.code(),
    '',
    ...declarations.flatMap((code) => [code, '']),
    contract,
    '',
  ].join('\n');
}

function actionCode(
  action: ActionDescription,
  transport: string,
  schema: (value: JsonSchema) => string,
  validation: ValidationDriver,
  imports: ImportSet,
): string {
  imports.add({ from: '@polycanal/core', names: ['action'] });
  const lines = [`transport: ${transport},`];

  if (action.input !== undefined) {
    lines.push(`input: ${inputCode(action.input, schema, validation, imports)},`);
  }

  lines.push(`output: ${schema(action.output)},`);

  const errors = Object.entries(action.errors ?? {});

  if (errors.length > 0) {
    lines.push(`errors: ${objectCode(errors.map(([key, value]) => [key, schema(value)]))},`);
  }

  if (action.meta !== undefined) {
    lines.push(`meta: ${JSON.stringify(action.meta)},`);
  }

  return `action(${objectCode(lines)})`;
}

function eventCode(
  event: EventDescription,
  transport: string,
  schema: (value: JsonSchema) => string,
  imports: ImportSet,
): string {
  imports.add({ from: '@polycanal/core', names: ['event'] });
  const lines = [`transport: ${transport},`];

  if (event.send !== undefined) {
    lines.push(`send: ${schema(event.send)},`);
  }

  if (event.receive !== undefined) {
    lines.push(`receive: ${schema(event.receive)},`);
  }

  if (event.meta !== undefined) {
    lines.push(`meta: ${JSON.stringify(event.meta)},`);
  }

  return `event(${objectCode(lines)})`;
}

function inputCode(
  input: InputDescription,
  schema: (value: JsonSchema) => string,
  validation: ValidationDriver,
  imports: ImportSet,
): string {
  if (input.kind === 'schema') {
    return schema(input.schema);
  }

  imports.add({ from: '@polycanal/core', names: ['input'] });

  const fields = input.fields.map((field): [string, string] => {
    const hasDefault = typeof field.schema === 'object' && field.schema.default !== undefined;
    let code = schema(field.schema);

    if (!field.required && !hasDefault) {
      code = imports.use(validation.optional({ code, imports: [] }));
    }

    const options = [
      field.source === undefined ? undefined : `source: ${quote(field.source)}`,
      field.alias === undefined ? undefined : `alias: ${quote(field.alias)}`,
      field.root ? 'root: true' : undefined,
    ].filter((option) => option !== undefined);

    return [field.name, options.length === 0 ? code : `{ ${options.join(', ')}, schema: ${code} }`];
  });

  return `input(${objectCode(fields)})`;
}

function buildTree(operations: readonly OperationDescription[]): TreeNode {
  const root: TreeNode = { children: new Map() };

  for (const operation of operations) {
    let node = root;

    operation.path.forEach((name, index) => {
      const existing = node.children.get(name);
      const isLeaf = index === operation.path.length - 1;

      if (isLeaf) {
        if (existing !== undefined) {
          fail(`duplicate operation "${operationId(operation)}"`);
        }

        node.children.set(name, operation);

        return;
      }

      if (existing !== undefined && !('children' in existing)) {
        fail(`"${operation.path.slice(0, index + 1).join('.')}" is both an operation and a namespace`);
      }

      const child = existing ?? { children: new Map() };
      node.children.set(name, child);
      node = child;
    });
  }

  return root;
}

function treeCode(node: TreeNode, operation: (value: OperationDescription) => string): string {
  return objectCode(
    [...node.children].map(([name, child]): [string, string] => [
      name,
      'children' in child ? treeCode(child, operation) : operation(child),
    ]),
  );
}

/** Multi-line object literal from `[key, code]` pairs or ready lines. */
function objectCode(entries: readonly ([string, string] | string)[]): string {
  if (entries.length === 0) {
    return '{}';
  }

  const lines = entries.map((entry) => (typeof entry === 'string' ? entry : `${key(entry[0])}: ${entry[1]},`));

  return `{\n${lines.map((line) => `  ${line.replace(/\n/g, '\n  ')}`).join('\n')}\n}`;
}

function key(name: string): string {
  return /^[A-Za-z_$][\w$]*$/.test(name) || /^\d+$/.test(name) ? name : quote(name);
}

function quote(value: string): string {
  return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}

function refName(ref: string): string {
  if (!ref.startsWith(SCHEMA_REF_PREFIX)) {
    fail(`unsupported schema reference "${ref}" (expected "${SCHEMA_REF_PREFIX}<name>")`);
  }

  return decodeURIComponent(ref.slice(SCHEMA_REF_PREFIX.length));
}

/** `user-profile` → `UserProfileSchema`, made unique. */
function schemaIdentifiers(names: readonly string[]): Map<string, string> {
  const used = new Set<string>();

  return new Map(
    names.map((name) => {
      const words = name.split(/[^A-Za-z0-9]+/).filter(Boolean);
      const pascal = words.map((word) => word[0]?.toUpperCase() + word.slice(1)).join('') || 'Anonymous';
      const base = `${/^\d/.test(pascal) ? `_${pascal}` : pascal}Schema`;
      let identifier = base;

      for (let index = 2; used.has(identifier); index++) {
        identifier = `${base}${index}`;
      }

      used.add(identifier);

      return [name, identifier];
    }),
  );
}

function fail(message: string): never {
  throw new TypeError(`generateContractSource: ${message}`);
}

class ImportSet {
  private readonly modules = new Map<string, Set<string>>();

  add(entry: CodeImport): void {
    const names = this.modules.get(entry.from) ?? new Set();

    for (const name of entry.names) {
      names.add(name);
    }

    this.modules.set(entry.from, names);
  }

  use(generated: GeneratedCode): string {
    for (const entry of generated.imports) {
      this.add(entry);
    }

    return generated.code;
  }

  code(): string {
    return [...this.modules]
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([from, names]) => `import { ${[...names].sort().join(', ')} } from '${from}';`)
      .join('\n');
  }
}
