import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { action, type ContractTree, createClient, defineContract, event, input } from '@polycanal/core';
import { fetchRest, rest, restBindingEmitter } from '@polycanal/rest';
import { zodDriver } from '@polycanal/zod';
import { afterAll, describe, expect, it, vi } from 'vitest';
import { z } from 'zod';
import { describeContract } from './describe.js';
import type { ContractDescription } from './description.js';
import { generateContractSource } from './generate.js';

const ws = (name: string) => ({ driver: 'ws', family: 'event' as const, sources: [], name });
const wsEmitter = {
  driver: 'ws',
  emit: (binding: { driver: string }) => ({
    code: `ws(${JSON.stringify((binding as { name?: string }).name)})`,
    imports: [{ from: './ws.js', names: ['ws'] }],
  }),
};
const options = { validation: zodDriver, bindings: [restBindingEmitter, wsEmitter] };

const outputDir = fileURLToPath(new URL('../.test-output/', import.meta.url));

afterAll(() => rmSync(outputDir, { recursive: true, force: true }));

/** Writes generated sources next to the tests and imports them, to check they compile and work for real. */
async function load(source: string, name: string): Promise<{ contract: ContractTree }> {
  mkdirSync(outputDir, { recursive: true });
  writeFileSync(`${outputDir}${name}.ts`, source);

  return import(`${outputDir}${name}.ts`);
}

const Node: z.ZodType<{ name: string; children: unknown[] }> = z.object({
  name: z.string(),
  get children() {
    return z.array(Node);
  },
});

const runtime = defineContract({
  auth: {
    login: action({
      transport: rest.post('/auth/login', { status: 200 }),
      input: z.object({ email: z.email(), password: z.string().min(8) }),
      output: z.object({ token: z.string() }),
      errors: { 401: z.object({ reason: z.string() }) },
      meta: { summary: 'Log in' },
    }),
  },
  households: {
    updateMemberRole: action({
      transport: rest.patch('/user/:userId'),
      input: input({
        householdId: z.string(),
        userId: { source: 'path', schema: z.string() },
        toUserId: { source: 'body', alias: 'userId', schema: z.string() },
        role: z.enum(['admin', 'member']),
        note: z.string().optional(),
        page: z.number().int().default(1),
      }),
      output: z.void(),
    }),
    tree: action({ transport: rest.get('/tree'), output: Node }),
  },
  notifications: event({ transport: ws('notification'), receive: z.object({ text: z.string() }) }),
});

describe('generateContractSource()', () => {
  it('generates a readable contract', () => {
    const source = generateContractSource(describeContract(runtime), options);

    expect(source).toContain('// Generated by Polycanal. Do not edit: regenerate instead.');
    expect(source).toContain("import { action, defineContract, event, input } from '@polycanal/core';");
    expect(source).toContain("import { rest } from '@polycanal/rest';");
    expect(source).toContain("import { ws } from './ws.js';");
    expect(source).toContain("import { z } from 'zod';");
    expect(source).toContain("transport: rest.post('/auth/login', { status: 200 }),");
    expect(source).toContain("userId: { source: 'path', schema: z.string() },");
    expect(source).toContain("toUserId: { source: 'body', alias: 'userId', schema: z.string() },");
    expect(source).toContain('note: z.string().optional(),');
    expect(source).toContain('page: z.number().int().default(1),');
    expect(source).toContain('output: z.void(),');
    expect(source).toContain('meta: {"summary":"Log in"},');
    expect(source).toContain('export const HouseholdsTreeOutputSchema = z.object({');
    expect(source).toContain('children: z.array(z.lazy(() => HouseholdsTreeOutputSchema)),');
    expect(source).toContain('output: HouseholdsTreeOutputSchema,');
  });

  it('generates code that works: same requests, same validation', async () => {
    const { contract } = await load(
      generateContractSource(describeContract({ auth: runtime.auth, households: runtime.households }), options),
      'roundtrip',
    );
    const fetchMock = vi.fn<typeof fetch>(async () => new Response(null, { status: 204 }));
    const server = createClient(contract as typeof runtime, {
      drivers: [fetchRest({ baseUrl: 'https://api.test', fetch: fetchMock })],
    });

    await server.households.updateMemberRole({ householdId: 'h1', userId: 'u1', toUserId: 'u2', role: 'admin' });

    expect(fetchMock.mock.calls[0]?.[0]).toBe('https://api.test/user/u1');
    expect(fetchMock.mock.calls[0]?.[1]?.body).toBe('{"householdId":"h1","userId":"u2","role":"admin","page":1}');
    await expect(server.auth.login({ email: 'nope', password: 'short' })).rejects.toMatchObject({ kind: 'input' });
  });

  it('generates named schemas and their references', async () => {
    const description: ContractDescription = {
      schemas: {
        user: {
          type: 'object',
          properties: { id: { type: 'string' }, manager: { $ref: '#/schemas/user' } },
          required: ['id'],
        },
        'user-list': { type: 'array', items: { $ref: '#/schemas/user' } },
      },
      operations: [
        {
          family: 'action',
          path: ['users', 'list'],
          binding: rest.get('/users'),
          output: { $ref: '#/schemas/user-list' },
        },
        {
          family: 'action',
          path: ['users', 'get'],
          binding: rest.get('/users/:id'),
          input: { kind: 'fields', fields: [{ name: 'id', schema: { type: 'string' }, required: true }] },
          output: { $ref: '#/schemas/user' },
        },
      ],
    };
    const source = generateContractSource(description, { ...options, exportName: 'api', banner: 'Custom banner' });

    expect(source.startsWith('// Custom banner\n')).toBe(true);
    expect(source).toContain(
      'export const UserSchema = z.object({\n  id: z.string(),\n  manager: z.lazy(() => UserSchema).optional(),\n});',
    );
    expect(source).toContain('export const UserListSchema = z.array(UserSchema);');
    expect(source).toContain('export const api = defineContract({');

    const loaded = (await load(source, 'named')) as unknown as { api: ContractTree; UserSchema: z.ZodType };
    expect(loaded.UserSchema.safeParse({ id: 'a', manager: { id: 'b' } }).success).toBe(true);
    expect(loaded.UserSchema.safeParse({ id: 'a', manager: { id: 1 } }).success).toBe(false);
  });

  it('quotes names that are not identifiers', () => {
    const source = generateContractSource(
      { operations: [{ family: 'action', path: ['user-admin', 'list'], binding: rest.get('/x'), output: true }] },
      options,
    );

    expect(source).toContain("'user-admin': {");
  });

  it.each<[string, ContractDescription, string]>([
    [
      'a missing emitter',
      {
        operations: [
          { family: 'action', path: ['x'], binding: { driver: 'grpc', family: 'action', sources: [] }, output: true },
        ],
      },
      'x: no binding emitter for driver "grpc"',
    ],
    [
      'an unknown reference',
      {
        operations: [{ family: 'action', path: ['x'], binding: rest.get('/x'), output: { $ref: '#/schemas/missing' } }],
      },
      'unknown schema reference "#/schemas/missing"',
    ],
    [
      'a foreign reference',
      { operations: [{ family: 'action', path: ['x'], binding: rest.get('/x'), output: { $ref: 'other.json#/a' } }] },
      'unsupported schema reference "other.json#/a"',
    ],
    [
      'a duplicate operation',
      {
        operations: [
          { family: 'action', path: ['x'], binding: rest.get('/x'), output: true },
          { family: 'action', path: ['x'], binding: rest.get('/y'), output: true },
        ],
      },
      'duplicate operation "x"',
    ],
    [
      'an operation used as a namespace',
      {
        operations: [
          { family: 'action', path: ['x'], binding: rest.get('/x'), output: true },
          { family: 'action', path: ['x', 'y'], binding: rest.get('/y'), output: true },
        ],
      },
      '"x" is both an operation and a namespace',
    ],
  ])('rejects %s', (_, description, message) => {
    expect(() => generateContractSource(description, options)).toThrow(message);
  });
});
